// The publish PR's body: what the job decided and why, then the change report with the verdict (changes.ts). GitHub
// caps a body at 65,536 characters; a longer one is cut at a line and points to the full report, which the workflow
// keeps as a run artifact.
import { renderChangeReport, type ChangeReport } from "../pipeline/changes.ts";
import type { Verdict } from "../review/verdict.ts";
import type { TestResult } from "./job.ts";

/** GitHub's limit on a PR or issue body, in characters. */
export const BODY_LIMIT = 65_536;

export interface PrBodyInput {
  today: string;
  report: ChangeReport;
  verdict: Verdict;
  tests: TestResult;
  /** The reviewer that ran (its provider and model), or why none did. */
  reviewer: { run: true; provider?: string | undefined; model: string } | { run: false; why: string };
  /** The capture folder the dataset was built from, e.g. "fixtures/2026-10-23-daily". */
  capture: string;
  runUrl?: string;
  /** Divergence issues whose confirmed recheck this refresh answers (#18). */
  answers?: number[];
}

export function prBody({ today, report, verdict, tests, reviewer, capture, runUrl, answers }: PrBodyInput): string {
  const problems = verdict.findings.filter((f) => f.severity === "problem").length;
  const out = [
    `Daily refresh of ${today} (Brasília), built from \`${capture}/\`${runUrl ? ` by [this run](${runUrl})` : ""}. Generated by the daily publish job: never edit this PR's data by hand.`,
    "",
    verdict.decision === "merge"
      ? "**Verdict: merge.** Every review layer passed, so the job merges this PR."
      : `**Verdict: needs-human.** ${problems} ${problems === 1 ? "problem stops" : "problems stop"} the automatic merge; the job labels this PR \`needs-human\` and leaves it open for the maintainer. The problems are listed under the verdict below.`,
    "",
    tests.ran === false
      ? `- Tests (\`pnpm verify\`): not run. ${tests.summary}`
      : `- Tests (\`pnpm verify\`, run by the job on this branch): ${tests.passed ? "passed" : "**failed**"}. ${tests.summary}`,
    `- LLM reviewer (layer 3): ${reviewer.run ? `${reviewer.provider ? `${reviewer.provider} ` : ""}\`${reviewer.model}\`` : `**not run: ${reviewer.why}**, which blocks the merge`}.`,
    ...(answers?.length ? [`- Answers the text-divergence reports ${answers.map((n) => `#${n}`).join(", ")}: their recheck saw Planalto's page print a dispositivo differently from the published dataset.`] : []),
  ];

  out.push("", renderChangeReport(report, verdict));
  return out.join("\n");
}

/** The body cut to GitHub's limit at a line boundary, with a pointer to the full report when cut. */
export function fitBody(body: string, runUrl?: string, limit = BODY_LIMIT): string {
  if (body.length <= limit) return body;
  const note = `\n\n---\n\n**Report truncated** at GitHub's ${limit.toLocaleString("en")}-character limit. The full report is the \`change-report\` artifact of ${runUrl ? `[the run](${runUrl})` : "the run"}.\n`;
  const cut = body.slice(0, limit - note.length);
  return `${cut.slice(0, Math.max(cut.lastIndexOf("\n"), 0))}${note}`;
}
